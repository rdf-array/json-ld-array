#!/usr/bin/env python3
"""Write management/array-syntax-uses.md: every file of the rdf-array suites that uses the proposed array syntax.

    python3 tools/array-syntax-uses.py [--check]

The syntax for reaching into sequences is a proposal under research: SPARQL-array's position patterns
((element))[index] and functions isSEQ, SEQLEN, SEQ and expr[i], and ShEx-array's Collection shape
expression ((shapeExpr))[min, max]. When it changes, this list is what a change has to rewrite. It scans
the test suites checked out beside this repository (the W3C forks and the contrib suites) and this
repository's documents; implementations are listed by their own repositories' grammars and tests.
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
REPOS = ['rdf-tests-array', 'json-ld-api-array', 'json-ld-streaming-array', 'shexTest-array',
         'rdf-tests-contrib', 'json-ld-api-contrib', 'shexTest-contrib', 'rdf-array']
SPARQL_POS = re.compile(r'\(\(.*?\)\)\s*\[\s*(?:\d+|\?\w+|\*)\s*\]')
SPARQL_FN = re.compile(r'\b(?:isSEQ|SEQLEN|SEQ)\s*\(|\?\w+\[\d+\]')
SHEX_COLL = re.compile(r'\(\(.*?\)\)\s*(?:\[\s*\d+\s*(?:,\s*(?:\d+|\*)?\s*)?\])?')
EXT = {'.rq': 'sparql', '.ru': 'sparql', '.shex': 'shex', '.md': 'doc'}


def shex_collections(f):
    """Collections in a ShExC file, counted by shex.js-array's parser: `((` also groups triple expressions,
    which no pattern tells apart from a Collection. A file it cannot parse counts as none."""
    import json
    import subprocess
    shexjs = HERE.parent / 'shex.js-array' / 'packages' / 'shex-cli' / 'bin' / 'shex-to-json'
    r = subprocess.run(['node', str(shexjs), str(f)], capture_output=True, text=True)
    if r.returncode:
        return 0
    return r.stdout.count('"type": "Collection"') + r.stdout.count('"type":"Collection"')


def main():
    rows = []
    for repo in REPOS:
        root = HERE.parent / repo
        if not root.exists():
            continue
        for f in sorted(root.rglob('*')):
            if f.suffix not in EXT or '.git' in f.parts or 'node_modules' in f.parts or f.name in ('array-syntax-uses.md', 'contrib-duplicates.md'):
                continue
            text = f.read_text(encoding='utf-8', errors='replace')
            kind = EXT[f.suffix]
            if kind == 'sparql':
                n = len(SPARQL_POS.findall(text)) + len(SPARQL_FN.findall(text))
            elif kind == 'shex':
                n = shex_collections(f)
            else:
                n = len(SPARQL_POS.findall(text)) + len(re.findall(r'\(\([^)\n]*\)\)\s*\[\s*\d', text))
            if n:
                rows.append((repo, f.relative_to(root).as_posix(), kind, n))
    lines = ['# Uses of the proposed array syntax', '',
             '*Generated by `tools/array-syntax-uses.py`; do not edit.*', '',
             'SPARQL-array reaches into a sequence with **position patterns** `((element))[index]` (index an integer, a '
             'variable or `*`) and the functions `isSEQ`, `SEQLEN`, `SEQ` and `expr[i]`; ShEx-array constrains one with the '
             '**Collection shape expression** `((shapeExpr))[min, max]`. Both are the syntax proposed today, deliberately '
             'alike, and expected to change with the ongoing research on array syntax. These are the files a change of '
             'syntax has to rewrite; the tests that use the SPARQL forms also say so with `mf:requires ra:PositionPatterns` '
             'or `ra:SequenceFunctions`, and the ShEx ones with `ra:CollectionShapeExpression`.', '',
             '| Repository | File | Language | Uses |', '|---|---|---|---|']
    lines += [f'| {r} | [{p}](https://github.com/rdf-array/{r}/blob/{"main" if r.endswith("contrib") or r == "rdf-array" else "rdf-sequences"}/{p}) | {k} | {n} |' for r, p, k, n in rows]
    text = '\n'.join(lines) + '\n'
    out = HERE / 'management' / 'array-syntax-uses.md'
    if '--check' in sys.argv:
        sys.exit(0 if out.exists() and out.read_text() == text else 'array-syntax-uses.md is out of date')
    out.write_text(text)
    print(f'array-syntax-uses.md: {len(rows)} files')


if __name__ == '__main__':
    main()
