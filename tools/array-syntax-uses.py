#!/usr/bin/env python3
"""Write management/array-syntax-uses.md: every file of the rdf-array suites that uses the proposed array syntax.

    python3 tools/array-syntax-uses.py [--check]

The syntax for reaching into sequences is a proposal under research (docs/array-syntax.md): SPARQL-array's
gaps `...` and `...?rest` in a sequence pattern, UNNEST, and the functions isSEQ, SEQLEN, SEQ, expr[i],
expr[m...n] and `IN ?seq`; ShEx-array's LIST shape expression. When it changes, this list is what a
change has to rewrite. It scans
the test suites checked out beside this repository (the W3C forks and the contrib suites) and this
repository's documents; implementations are listed by their own repositories' grammars and tests.
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
REPOS = ['rdf-tests-array', 'json-ld-api-array', 'json-ld-streaming-array', 'shexTest-array',
         'rdf-tests-contrib', 'json-ld-api-contrib', 'shexTest-contrib', 'rdf-array']
SPARQL_POS = re.compile(r'(?<![\w:.-])\.\.\.(?=[\s?)\]]|$)|\bUNNEST\s*\(', re.M)   # gaps, named gaps, UNNEST
SPARQL_FN = re.compile(r'\b(?:isSEQ|SEQLEN|SEQ)\s*\(|\?\w+\[|\bIN\s+(?:\?\w+|SEQ\s*\()')   # ?x[ without a space: `?p [ … ]` is a bnode
SHEX_LIST = re.compile(r'\bLIST\s*[({*+?]')
DOC_USE = re.compile(r'\([^()\n]*(?<![\w:.-])\.\.\.(?=[\s?)])[^()\n]*\)|\bUNNEST\s*\(|\bLIST\s*[({*+?]')   # in prose, a gap only inside ( )
EXT = {'.rq': 'sparql', '.ru': 'sparql', '.shex': 'shex', '.md': 'doc'}


def shex_collections(f):
    """LIST shape expressions in a ShExC file: the keyword followed by `(`, a cardinality or `{m,n}`."""
    return len(SHEX_LIST.findall(f.read_text(encoding='utf-8', errors='replace')))


def main():
    rows = []
    for repo in REPOS:
        root = HERE.parent / repo
        if not root.exists():
            continue
        for f in sorted(root.rglob('*')):
            if f.suffix not in EXT or '.git' in f.parts or 'node_modules' in f.parts or f.name in ('array-syntax-uses.md', 'contrib-duplicates.md'):
                continue
            text = f.read_text(encoding='utf-8', errors='replace')
            kind = EXT[f.suffix]
            if kind == 'sparql':
                code = re.sub(r'(?m)(^|\s)#.*$', '', text)   # comments out: `# ...` is prose
                n = len(SPARQL_POS.findall(code)) + len(SPARQL_FN.findall(code))
            elif kind == 'shex':
                n = shex_collections(f)
            else:
                n = len(DOC_USE.findall(text))
            if n:
                rows.append((repo, f.relative_to(root).as_posix(), kind, n))
    lines = ['# Uses of the array syntax', '',
             '*Generated by `tools/array-syntax-uses.py`; do not edit.*', '',
             'SPARQL-array reaches into a sequence with **gaps** `...` and `...?rest` in a sequence pattern, with '
             '`UNNEST(expr AS ?x AT ?i)`, and with the functions `isSEQ`, `SEQLEN`, `SEQ`, `expr[i]`, `expr[m...n]` and '
             '`IN ?seq`; ShEx-array constrains one with the **LIST shape expression** `LIST ( regex )` and `LIST card x` '
             '([array-syntax.md](../docs/array-syntax.md), which replaced the first proposal `((x))[i]` and '
             '`((shapeExpr))[m, n]`). These are the files a change of syntax has to rewrite; the tests that use the '
             'SPARQL forms also say so with `mf:requires ra:GapPatterns`, `ra:Unnest` or `ra:SequenceFunctions`, and '
             'the ShEx ones with `ra:ListShapeExpression`.', '',
             '| Repository | File | Language | Uses |', '|---|---|---|---|']
    lines += [f'| {r} | [{p}](https://github.com/rdf-array/{r}/blob/rdf-sequences/{p}) | {k} | {n} |' for r, p, k, n in rows]
    text = '\n'.join(lines) + '\n'
    out = HERE / 'management' / 'array-syntax-uses.md'
    if '--check' in sys.argv:
        sys.exit(0 if out.exists() and out.read_text() == text else 'array-syntax-uses.md is out of date')
    out.write_text(text)
    print(f'array-syntax-uses.md: {len(rows)} files')


if __name__ == '__main__':
    main()
