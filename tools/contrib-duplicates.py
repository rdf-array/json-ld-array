#!/usr/bin/env python3
"""Write management/contrib-duplicates.md: which implementation tests each rdf-array contrib test duplicates.

    python3 tools/contrib-duplicates.py [--check]

Reads duplicates.json from the contrib repositories checked out beside this one (rdf-tests-contrib,
json-ld-api-contrib, shexTest-contrib, data-shapes-contrib), each written by that repository's bin/build.py. The
implementations keep their own tests for now; this list says which of them a contrib manifest now
covers, for the day each implementation walks the contrib manifests instead.
"""
import json
import pathlib
import sys
from collections import defaultdict

HERE = pathlib.Path(__file__).resolve().parent.parent
SUITES = ['rdf-tests-contrib', 'json-ld-api-contrib', 'shexTest-contrib', 'data-shapes-contrib']


def main():
    by_impl = defaultdict(list)
    counts = {}
    for suite in SUITES:
        f = HERE.parent / suite / 'duplicates.json'
        if not f.exists():
            sys.exit(f'{f} is missing: check out rdf-array/{suite} beside this repository and run its bin/build.py')
        tests = json.loads(f.read_text())['tests']
        counts[suite] = len(tests)
        for t in tests:
            for d in t['duplicates']:
                impl, _, where = d.partition(' ')
                by_impl[impl].append((where, suite, t['test']))
    lines = ['# Implementation tests duplicated by the contrib suites', '',
             '*Generated by `tools/contrib-duplicates.py` from the contrib repositories\' `duplicates.json`; do not edit.*', '',
             'The contrib suites ([rdf-tests-contrib](https://github.com/rdf-array/rdf-tests-contrib), '
             '[json-ld-api-contrib](https://github.com/rdf-array/json-ld-api-contrib), '
             '[shexTest-contrib](https://github.com/rdf-array/shexTest-contrib), '
             '[data-shapes-contrib](https://github.com/rdf-array/data-shapes-contrib)) collect tests that every rdf-array '
             'implementation can share but that no W3C suite contains. Each was seeded from an implementation\'s own tests, '
             'which stay where they are for now. This list says, implementation by implementation, which of its tests a '
             'contrib test reproduces, so that an implementation that walks the contrib manifests can retire or keep them '
             'knowingly.', '',
             '| Suite | Contrib tests with a source |', '|---|---|']
    lines += [f'| [{s}](https://github.com/rdf-array/{s}) | {n} |' for s, n in counts.items()]
    for impl in sorted(by_impl):
        lines += ['', f'## {impl}', '', '| Implementation test | Duplicated by |', '|---|---|']
        for where, suite, test in sorted(by_impl[impl]):
            lines.append(f'| {where.replace("|", "/")} | {suite} `{test}` |')
    text = '\n'.join(lines) + '\n'
    out = HERE / 'management' / 'contrib-duplicates.md'
    if '--check' in sys.argv:
        sys.exit(0 if out.exists() and out.read_text() == text else 'contrib-duplicates.md is out of date')
    out.write_text(text)
    print(f'contrib-duplicates.md: {sum(len(v) for v in by_impl.values())} rows over {len(by_impl)} implementations')


if __name__ == '__main__':
    main()
